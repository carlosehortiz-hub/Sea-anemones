"""Stage 7 - query: run the documented SPARQL and SQL queries, save results.

* SPARQL (queries/*.rq) runs over the built graph with rdflib.
* SQL (queries/sql/*.sql) runs in DuckDB over the canonical tables, loaded with
  the dtypes LinkML declares (the same loader as the data-quality stage).

Each query file starts with `title:`, `question:` and `why:` comment lines; the
report is generated from them, so documentation and query cannot drift apart.
Results go to queries/results/<name>.csv and reports/query_results.md.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from pathlib import Path

import duckdb
import pandas as pd
import rdflib

from anemone_kg.cli import stage
from anemone_kg.config import Config
from anemone_kg.rdf.vocab import load_registry
from anemone_kg.stages.validate import load_tables

log = logging.getLogger(__name__)
SHOWN_ROWS = 15


@dataclass(frozen=True)
class Query:
    path: Path
    kind: str  # sparql | sql
    title: str
    question: str
    why: str

    @property
    def name(self) -> str:
        return self.path.stem

    @property
    def text(self) -> str:
        return self.path.read_text(encoding="utf-8")


def parse_header(path: Path, kind: str) -> Query:
    marker = "#" if kind == "sparql" else "--"
    meta: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(rf"^{re.escape(marker)}\s*(title|question|why):\s*(.+)$", line)
        if m:
            meta[m.group(1)] = m.group(2).strip()
        elif meta.get("why") and not line.startswith(marker):
            break
        elif line.startswith(marker) and "why" in meta:  # continuation of 'why'
            meta["why"] += " " + line.lstrip(marker).strip()
    missing = {"title", "question", "why"} - set(meta)
    if missing:
        raise ValueError(f"{path.name}: header lacks {sorted(missing)}")
    return Query(path, kind, meta["title"], meta["question"], meta["why"])


def discover(root: Path) -> list[Query]:
    qdir = root / "queries"
    return [parse_header(p, "sparql") for p in sorted(qdir.glob("*.rq"))] + [
        parse_header(p, "sql") for p in sorted((qdir / "sql").glob("*.sql"))
    ]


def _term(v) -> object:
    if v is None:
        return None
    if isinstance(v, rdflib.Literal):
        return v.toPython() if not isinstance(v.toPython(), rdflib.Literal) else str(v)
    return str(v)


def run_sparql(q: Query, g: rdflib.Graph) -> pd.DataFrame:
    res = g.query(q.text)
    cols = [str(v) for v in res.vars]
    return pd.DataFrame([[_term(row[c]) for c in cols] for row in res], columns=cols)


def duck(tables: dict[str, pd.DataFrame]) -> duckdb.DuckDBPyConnection:
    con = duckdb.connect()
    for name, df in tables.items():
        con.register(name, df)
    return con


def run_sql(q: Query, con: duckdb.DuckDBPyConnection) -> pd.DataFrame:
    return con.execute(q.text).df()


def run_all(cfg: Config) -> dict[str, tuple[Query, pd.DataFrame]]:
    g = rdflib.Graph().parse(cfg.path("processed") / "anemone_kg.ttl")
    con = duck(load_tables(cfg))
    out = {}
    for q in discover(cfg.root):
        df = run_sparql(q, g) if q.kind == "sparql" else run_sql(q, con)
        out[q.name] = (q, df)
    return out


def _compact(value: str, prefixes: dict[str, str]) -> str:
    """Report-only CURIE compaction; the CSVs keep full IRIs for reuse."""
    for prefix, ns in sorted(prefixes.items(), key=lambda kv: -len(kv[1])):
        if value.startswith(ns) and len(value) > len(ns):
            return f"{prefix}:{value[len(ns) :]}"
    return value


def _md_table(df: pd.DataFrame, prefixes: dict[str, str]) -> str:
    shown = df.head(SHOWN_ROWS).copy()
    for c in shown.columns:
        shown[c] = shown[c].map(
            lambda v: (
                ""
                if v is None or (isinstance(v, float) and v != v)
                else _compact(str(v), prefixes).replace("|", "\\|")
            )
        )
    text = shown.to_markdown(index=False)
    if len(df) > SHOWN_ROWS:
        text += f"\n\n... {len(df) - SHOWN_ROWS} more rows in the CSV."
    return text


def to_markdown(results: dict[str, tuple[Query, pd.DataFrame]], prefixes: dict[str, str]) -> str:
    lines = [
        "# Query results",
        "",
        "Generated by `python -m anemone_kg run query`. SPARQL runs over "
        "`data/processed/anemone_kg.ttl` (rdflib); SQL runs in DuckDB over the canonical "
        "tables. Full results are in `queries/results/`.",
        "",
        "| query | engine | rows | question |",
        "|---|---|---:|---|",
    ]
    for name, (q, df) in results.items():
        engine = "SPARQL" if q.kind == "sparql" else "SQL (DuckDB)"
        lines.append(
            f"| [{name}](#{name.replace('_', '-')}) | {engine} | {len(df)} | {q.question} |"
        )
    for name, (q, df) in results.items():
        rel = q.path.relative_to(q.path.parents[1] if q.kind == "sql" else q.path.parent)
        lines += [
            "",
            f"## {name}",
            "",
            f"**{q.title}.** {q.question}",
            "",
            f"*Why:* {q.why}",
            "",
            f"Source: `queries/{rel}`",
            "",
            _md_table(df, prefixes),
        ]
    lines.append("")
    return "\n".join(lines)


@stage("query")
def query(cfg: Config) -> None:
    results = run_all(cfg)
    out = cfg.root / "queries" / "results"
    out.mkdir(parents=True, exist_ok=True)
    for name, (_, df) in results.items():
        df.to_csv(out / f"{name}.csv", index=False)
        log.info("[query] %-40s %4d rows", name, len(df))
    prefixes = load_registry(cfg.root / "model" / "terms.yaml").prefixes
    (cfg.path("reports") / "query_results.md").write_text(
        to_markdown(results, prefixes), encoding="utf-8"
    )
